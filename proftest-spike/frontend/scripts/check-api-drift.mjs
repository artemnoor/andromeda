import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const sourceUrl = process.env.OPENAPI_URL ?? "http://127.0.0.1:8100/openapi.json";
const response = await fetch(sourceUrl);
if (!response.ok) throw new Error(`OpenAPI request failed with ${response.status}`);
const ast = await openapiTS(await response.json());
const expected = `/* Generated by scripts/generate-api.mjs. Do not edit. */\n\n${astToString(ast)}`;
// Git may check out generated text with CRLF on Windows. Compare contract
// content independently of the checkout line-ending policy.
const actual = (await readFile(resolve("src/api/generated.openapi.ts"), "utf8")).replace(/\r\n/g, "\n");
if (actual !== expected) throw new Error("Generated OpenAPI types are stale. Run npm run generate-api.");
console.log("Spike frontend OpenAPI types match the running API.");
