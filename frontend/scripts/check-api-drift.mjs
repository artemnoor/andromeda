import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const expected = resolve("src/api/generated.ts");
const tempSpec = resolve(".tmp-openapi.json");
const sourceFile = process.env.OPENAPI_FILE ?? tempSpec;
if (!process.env.OPENAPI_FILE) {
  const response = await fetch(process.env.OPENAPI_URL ?? "http://127.0.0.1:8000/openapi.json");
  if (!response.ok) throw new Error(`OpenAPI request failed with ${response.status}`);
  await (await import("node:fs/promises")).writeFile(tempSpec, JSON.stringify(await response.json()), "utf8");
}
// Git may check out generated text with CRLF on Windows. Compare the contract
// after normalizing line endings so the drift gate checks content, not checkout
// policy.
const before = (await readFile(expected, "utf8")).replace(/\r\n/g, "\n");
const schema = JSON.parse(await readFile(sourceFile, "utf8"));
const ast = await openapiTS(schema);
const after = `/* Generated by scripts/generate-api.mjs. Do not edit. */\n\n${astToString(ast)}`;
if (before !== after) {
  throw new Error("Generated frontend client is stale. Run npm run generate-api and review the contract change.");
}
console.log("Frontend client matches the current OpenAPI specification.");
